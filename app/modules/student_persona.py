def persona_block(key: Optional[str]) -> str:
    """返回要拼进系统提示的性格段落；key 不合法或没选就返回空串。"""
    if not key:
        return ""
    return _PERSONA_BLOCKS.get(key, "")


def mock_phrase(key: Optional[str], kind: str) -> str:
    """无密钥 Mock 助手取一句性格话术；没选性格就退化成学长型。"""
    block = _MOCK_PHRASES.get(key) or _MOCK_PHRASES["senpai"]
    return block.get(kind, "")


def is_valid(key: Optional[str]) -> bool:
    """判断前端传来的性格 key 合不合法。"""
    return bool(key) and any(p["key"] == key for p in STUDENT_PERSONAS)
